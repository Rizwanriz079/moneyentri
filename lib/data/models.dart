/// Plain immutable data models. Every model round-trips through JSON so the
/// whole app state can be saved as one document.
library;

double _d(Object? v) => (v as num?)?.toDouble() ?? 0;
int _i(Object? v) => (v as num?)?.toInt() ?? 0;

class TxLink {
  const TxLink({required this.kind, required this.refId, required this.paymentId});
  final String kind; // 'loan' | 'bill'
  final String refId, paymentId;

  Map<String, dynamic> toJson() => {'kind': kind, 'refId': refId, 'paymentId': paymentId};
  factory TxLink.fromJson(Map<String, dynamic> j) => TxLink(kind: j['kind'], refId: j['refId'], paymentId: j['paymentId']);
}

class Transaction {
  const Transaction({
    required this.id,
    required this.type,
    required this.amount,
    required this.categoryId,
    required this.date,
    required this.note,
    required this.method,
    required this.createdAt,
    this.link,
  });

  final String id;
  final String type; // 'income' | 'expense'
  final double amount;
  final String categoryId, date, note, method;
  final int createdAt;

  /// Set when the transaction was generated by paying an EMI or a bill.
  final TxLink? link;

  bool get isIncome => type == 'income';

  Transaction copyWith({
    String? type,
    double? amount,
    String? categoryId,
    String? date,
    String? note,
    String? method,
    TxLink? link,
    bool clearLink = false,
  }) => Transaction(
    id: id,
    type: type ?? this.type,
    amount: amount ?? this.amount,
    categoryId: categoryId ?? this.categoryId,
    date: date ?? this.date,
    note: note ?? this.note,
    method: method ?? this.method,
    createdAt: createdAt,
    link: clearLink ? null : (link ?? this.link),
  );

  Map<String, dynamic> toJson() => {
    'id': id,
    'type': type,
    'amount': amount,
    'categoryId': categoryId,
    'date': date,
    'note': note,
    'method': method,
    'createdAt': createdAt,
    if (link != null) 'link': link!.toJson(),
  };

  factory Transaction.fromJson(Map<String, dynamic> j) => Transaction(
    id: j['id'],
    type: j['type'],
    amount: _d(j['amount']),
    categoryId: j['categoryId'],
    date: j['date'],
    note: j['note'] ?? '',
    method: j['method'] ?? 'cash',
    createdAt: _i(j['createdAt']),
    link: j['link'] == null ? null : TxLink.fromJson(Map<String, dynamic>.from(j['link'])),
  );
}

class Budget {
  const Budget({this.monthly = 0, this.categories = const {}});
  final double monthly;
  final Map<String, double> categories;

  Map<String, dynamic> toJson() => {'monthly': monthly, 'categories': categories};
  factory Budget.fromJson(Map<String, dynamic> j) =>
      Budget(monthly: _d(j['monthly']), categories: (j['categories'] as Map? ?? {}).map((k, v) => MapEntry(k as String, _d(v))));
}

class GoalEntry {
  const GoalEntry({required this.id, required this.amount, required this.date, required this.note});
  final String id;
  final double amount; // positive = deposit, negative = withdrawal
  final String date, note;

  Map<String, dynamic> toJson() => {'id': id, 'amount': amount, 'date': date, 'note': note};
  factory GoalEntry.fromJson(Map<String, dynamic> j) =>
      GoalEntry(id: j['id'], amount: _d(j['amount']), date: j['date'], note: j['note'] ?? '');
}

class Goal {
  const Goal({
    required this.id,
    required this.name,
    required this.target,
    this.deadline,
    required this.icon,
    required this.color,
    required this.entries,
    required this.createdAt,
  });

  final String id, name, icon, color;
  final double target;
  final String? deadline;
  final List<GoalEntry> entries;
  final int createdAt;

  double get saved => (entries.fold<double>(0, (s, e) => s + e.amount) * 100).roundToDouble() / 100;

  Goal copyWith({
    String? name,
    double? target,
    String? deadline,
    bool clearDeadline = false,
    String? icon,
    String? color,
    List<GoalEntry>? entries,
  }) => Goal(
    id: id,
    name: name ?? this.name,
    target: target ?? this.target,
    deadline: clearDeadline ? null : (deadline ?? this.deadline),
    icon: icon ?? this.icon,
    color: color ?? this.color,
    entries: entries ?? this.entries,
    createdAt: createdAt,
  );

  Map<String, dynamic> toJson() => {
    'id': id,
    'name': name,
    'target': target,
    if (deadline != null) 'deadline': deadline,
    'icon': icon,
    'color': color,
    'entries': entries.map((e) => e.toJson()).toList(),
    'createdAt': createdAt,
  };

  factory Goal.fromJson(Map<String, dynamic> j) => Goal(
    id: j['id'],
    name: j['name'],
    target: _d(j['target']),
    deadline: j['deadline'],
    icon: j['icon'] ?? 'flag',
    color: j['color'] ?? '#6366F1',
    entries: [for (final e in (j['entries'] as List? ?? [])) GoalEntry.fromJson(Map<String, dynamic>.from(e))],
    createdAt: _i(j['createdAt']),
  );
}

class ReminderConfig {
  const ReminderConfig({this.enabled = true, this.paused = false, this.offsets = const [7, 3, 1, 0]});
  final bool enabled, paused;

  /// Days before the due date; 0 = on the due date.
  final List<int> offsets;

  ReminderConfig copyWith({bool? enabled, bool? paused, List<int>? offsets}) =>
      ReminderConfig(enabled: enabled ?? this.enabled, paused: paused ?? this.paused, offsets: offsets ?? this.offsets);

  Map<String, dynamic> toJson() => {'enabled': enabled, 'paused': paused, 'offsets': offsets};
  factory ReminderConfig.fromJson(Map<String, dynamic> j) => ReminderConfig(
    enabled: j['enabled'] ?? true,
    paused: j['paused'] ?? false,
    offsets: [for (final o in (j['offsets'] as List? ?? [])) _i(o)],
  );
}

class Loan {
  const Loan({
    required this.id,
    required this.name,
    required this.type,
    required this.bank,
    required this.totalAmount,
    required this.openingBalance,
    required this.emi,
    required this.interestRate,
    required this.startDate,
    required this.tenureMonths,
    required this.reminders,
    required this.trackingFrom,
    required this.createdAt,
  });

  final String id, name, type, bank;
  final double totalAmount;

  /// Outstanding principal when the loan was added to the app.
  final double openingBalance;
  final double emi;

  /// Annual interest rate in percent.
  final double interestRate;

  /// Date of the first EMI. Later EMIs fall on the same day each month.
  final String startDate;
  final int tenureMonths;
  final ReminderConfig reminders;

  /// EMIs due before this date are treated as settled before tracking began.
  final String trackingFrom;
  final int createdAt;

  Loan copyWith({
    String? name,
    String? type,
    String? bank,
    double? totalAmount,
    double? openingBalance,
    double? emi,
    double? interestRate,
    String? startDate,
    int? tenureMonths,
    ReminderConfig? reminders,
    String? trackingFrom,
  }) => Loan(
    id: id,
    name: name ?? this.name,
    type: type ?? this.type,
    bank: bank ?? this.bank,
    totalAmount: totalAmount ?? this.totalAmount,
    openingBalance: openingBalance ?? this.openingBalance,
    emi: emi ?? this.emi,
    interestRate: interestRate ?? this.interestRate,
    startDate: startDate ?? this.startDate,
    tenureMonths: tenureMonths ?? this.tenureMonths,
    reminders: reminders ?? this.reminders,
    trackingFrom: trackingFrom ?? this.trackingFrom,
    createdAt: createdAt,
  );

  Map<String, dynamic> toJson() => {
    'id': id,
    'name': name,
    'type': type,
    'bank': bank,
    'totalAmount': totalAmount,
    'openingBalance': openingBalance,
    'emi': emi,
    'interestRate': interestRate,
    'startDate': startDate,
    'tenureMonths': tenureMonths,
    'reminders': reminders.toJson(),
    'trackingFrom': trackingFrom,
    'createdAt': createdAt,
  };

  factory Loan.fromJson(Map<String, dynamic> j) => Loan(
    id: j['id'],
    name: j['name'],
    type: j['type'] ?? 'other',
    bank: j['bank'] ?? '',
    totalAmount: _d(j['totalAmount']),
    openingBalance: _d(j['openingBalance']),
    emi: _d(j['emi']),
    interestRate: _d(j['interestRate']),
    startDate: j['startDate'],
    tenureMonths: _i(j['tenureMonths']),
    reminders: ReminderConfig.fromJson(Map<String, dynamic>.from(j['reminders'] ?? {})),
    trackingFrom: j['trackingFrom'] ?? j['startDate'],
    createdAt: _i(j['createdAt']),
  );
}

class Bill {
  const Bill({
    required this.id,
    required this.name,
    required this.category,
    required this.amount,
    required this.frequency,
    required this.startDate,
    this.endDate,
    required this.reminders,
    required this.trackingFrom,
    required this.note,
    required this.createdAt,
  });

  final String id, name, category;
  final double amount;
  final String frequency; // weekly | monthly | quarterly | yearly

  /// First due date. Later dates repeat at the chosen frequency.
  final String startDate;
  final String? endDate;
  final ReminderConfig reminders;
  final String trackingFrom, note;
  final int createdAt;

  Bill copyWith({
    String? name,
    String? category,
    double? amount,
    String? frequency,
    String? startDate,
    String? endDate,
    bool clearEnd = false,
    ReminderConfig? reminders,
    String? note,
  }) => Bill(
    id: id,
    name: name ?? this.name,
    category: category ?? this.category,
    amount: amount ?? this.amount,
    frequency: frequency ?? this.frequency,
    startDate: startDate ?? this.startDate,
    endDate: clearEnd ? null : (endDate ?? this.endDate),
    reminders: reminders ?? this.reminders,
    trackingFrom: trackingFrom,
    note: note ?? this.note,
    createdAt: createdAt,
  );

  Map<String, dynamic> toJson() => {
    'id': id,
    'name': name,
    'category': category,
    'amount': amount,
    'frequency': frequency,
    'startDate': startDate,
    if (endDate != null) 'endDate': endDate,
    'reminders': reminders.toJson(),
    'trackingFrom': trackingFrom,
    'note': note,
    'createdAt': createdAt,
  };

  factory Bill.fromJson(Map<String, dynamic> j) => Bill(
    id: j['id'],
    name: j['name'],
    category: j['category'] ?? 'other',
    amount: _d(j['amount']),
    frequency: j['frequency'] ?? 'monthly',
    startDate: j['startDate'],
    endDate: j['endDate'],
    reminders: ReminderConfig.fromJson(Map<String, dynamic>.from(j['reminders'] ?? {})),
    trackingFrom: j['trackingFrom'] ?? j['startDate'],
    note: j['note'] ?? '',
    createdAt: _i(j['createdAt']),
  );
}

class Payment {
  const Payment({
    required this.id,
    required this.kind,
    required this.refId,
    required this.dueDate,
    required this.period,
    required this.amount,
    this.principal,
    this.interest,
    this.balanceAfter,
    required this.paidOn,
    required this.method,
    required this.transactionId,
    required this.createdAt,
  });

  final String id, kind, refId;

  /// Scheduled due date of the installment that was paid.
  final String dueDate;

  /// Matching key for the installment (YYYY-MM, or YYYY-MM-DD for weekly).
  final String period;
  final double amount;
  final double? principal, interest;

  /// Outstanding principal after this payment (loans only).
  final double? balanceAfter;
  final String paidOn, method, transactionId;
  final int createdAt;

  Payment copyWith({String? paidOn, String? method}) => Payment(
    id: id,
    kind: kind,
    refId: refId,
    dueDate: dueDate,
    period: period,
    amount: amount,
    principal: principal,
    interest: interest,
    balanceAfter: balanceAfter,
    paidOn: paidOn ?? this.paidOn,
    method: method ?? this.method,
    transactionId: transactionId,
    createdAt: createdAt,
  );

  Map<String, dynamic> toJson() => {
    'id': id,
    'kind': kind,
    'refId': refId,
    'dueDate': dueDate,
    'period': period,
    'amount': amount,
    if (principal != null) 'principal': principal,
    if (interest != null) 'interest': interest,
    if (balanceAfter != null) 'balanceAfter': balanceAfter,
    'paidOn': paidOn,
    'method': method,
    'transactionId': transactionId,
    'createdAt': createdAt,
  };

  factory Payment.fromJson(Map<String, dynamic> j) => Payment(
    id: j['id'],
    kind: j['kind'],
    refId: j['refId'],
    dueDate: j['dueDate'],
    period: j['period'],
    amount: _d(j['amount']),
    principal: (j['principal'] as num?)?.toDouble(),
    interest: (j['interest'] as num?)?.toDouble(),
    balanceAfter: (j['balanceAfter'] as num?)?.toDouble(),
    paidOn: j['paidOn'],
    method: j['method'] ?? 'bank',
    transactionId: j['transactionId'] ?? '',
    createdAt: _i(j['createdAt']),
  );
}

class Settings {
  const Settings({
    this.name = '',
    this.email = '',
    this.currency = 'INR',
    this.theme = 'light',
    this.notificationsEnabled = true,
    this.reminderHour = 9,
  });

  final String name, email, currency;
  final String theme; // system | light | dark
  final bool notificationsEnabled;

  /// Hour of day (0-23) at which reminders fire.
  final int reminderHour;

  Settings copyWith({String? name, String? email, String? currency, String? theme, bool? notificationsEnabled, int? reminderHour}) =>
      Settings(
        name: name ?? this.name,
        email: email ?? this.email,
        currency: currency ?? this.currency,
        theme: theme ?? this.theme,
        notificationsEnabled: notificationsEnabled ?? this.notificationsEnabled,
        reminderHour: reminderHour ?? this.reminderHour,
      );

  Map<String, dynamic> toJson() => {
    'name': name,
    'email': email,
    'currency': currency,
    'theme': theme,
    'notificationsEnabled': notificationsEnabled,
    'reminderHour': reminderHour,
  };

  factory Settings.fromJson(Map<String, dynamic> j) => Settings(
    name: j['name'] ?? '',
    email: j['email'] ?? '',
    currency: j['currency'] ?? 'INR',
    theme: j['theme'] ?? 'light',
    notificationsEnabled: j['notificationsEnabled'] ?? true,
    reminderHour: _i(j['reminderHour'] ?? 9),
  );
}

